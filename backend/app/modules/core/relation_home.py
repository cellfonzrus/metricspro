def schema_of(table):
    """The schema that holds `table`. Raises `UnknownRelation` rather than assuming one."""
    key = str(table or "").strip().lower()
    try:
        return SCHEMA_OF[key]
    except KeyError:
        raise UnknownRelation(
            f"no migration in database/migrations/ creates a relation named '{key}', so this module "
            f"cannot say which schema holds it — add the migration (and the entry the lock will ask "
            f"for) rather than guessing a schema at the call site") from None


def reader(client, table, select="*"):
    """`client.schema(<its own schema>).table(table).select(select)` — the dereference a reader that
    takes a table BY NAME must use instead of hard-coding one schema for all of them."""
    return client.schema(schema_of(table)).table(table).select(select)
