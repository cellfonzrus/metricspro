"""WHICH SCHEMA HOLDS THIS RELATION — the ONE home of that fact (index §CORE-30).

THE DEFECT THAT MADE THIS NECESSARY, measured on production 2026-10-31. A reader that hard-codes a
schema and takes the TABLE as an argument cannot know where the table lives, and nothing checked.
`commcalc/router._calc_inputs` — the gathering of every read the full Run Calculation makes — is
exactly that shape: `client.schema('commcalc').table(table)`. Two of the names passed to it,
`employees` and `stores`, are `storeops` relations. While that reader swallowed its exceptions the
two reads returned [] and the calculation ran on nothing; once `core.feed_read.read_all` was made to
RAISE rather than mistake a failed read for a small feed, the same two reads began killing the whole
calculation at its first line. Every tenant, every month: LuxeLink `error` for June-October,
Cellfonz R Us for July-October, each one *"Could not find the table 'commcalc.employees' in the
schema cache"*. For about eight weeks no upload, no plan edit and no Run Calculation button could
recalculate anything, and the stored figures were whatever the last run before the change had left.

THE CLASS, NOT THE INSTANCE. The instance is "employees is read from the wrong schema". The class is
**a relation's schema is a fact, and it had no home** — so every reader that takes a table by name
carried its own assumption. The fact lives here now, every such reader dereferences it, and nothing
guesses: `schema_of` RAISES on a relation it does not know, because a default is how this shipped.

DERIVED FROM THE SCHEMA OF TRUTH, NOT KEPT IN STEP BY HAND. `database/migrations/` is this platform's
schema of truth (CLAUDE.md), and `harness_relation_home_lock.py` re-derives this map from every
`create table <schema>.<relation>` in it and fails the build on any disagreement, on a relation named
here that no migration creates, and on a schema-defaulting reader that stops dereferencing this
module. So this map cannot drift from the database, and the bug cannot come back wearing a new table
name. As at 2026-10-31 the migrations create 504 relations and NO relation name appears in two
schemas, which is why one name maps to one schema and the lock asserts that too.

Stdlib only, no I/O at import — safe to import from the router, the sweeps, a harness and the test
database double (which refuses a wrong-schema read precisely because it reads this map).
"""

