// THE ONE HOME for "what does a colour literal become on the dark theme" (index §CORE-15).
//
// The app draws its chrome from the tokens at the top of globals.css, but 377 page files also carry
// ~4,900 colour LITERALS in inline `style={{…}}` props — alert tints, status text, hairlines. An inline
// style cannot be overridden by a theme stylesheet (inline wins over every rule short of !important), so
// a dark theme that only redefines the chrome tokens leaves those literals glowing pale on black.
//
// So each literal becomes a token, defined in `:root` as ITSELF — which is why the light theme is
// byte-identical by construction, not by inspection — and redefined under the dark theme as the derived
// counterpart below. Call sites dereference the token and spell no colour.
//
// The token is keyed by ROLE as well as value, `--c-bg-<hex>` / `--c-fg-<hex>`, because "what does this
// colour become" is not a fact about the value alone: `#fff` is a page's white panel 20 times and the
// white LETTERING on a coloured button 92 times, and a dark theme must darken the first while leaving
// the second alone. The role is read from the CSS property at the call site, never guessed.
//
// Run `node theme_palette.mjs --write` to regenerate the blocks in globals.css; `prove_theme_tokens.mjs`
// regenerates and FAILS THE BUILD if the file has drifted or a new literal has appeared at a call site.
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

export const HERE = dirname(fileURLToPath(import.meta.url))
export const SRC = join(HERE, 'src')
export const CSS = join(SRC, 'app', 'globals.css')
export const BEGIN = '/* === palette tokens: generated by theme_palette.mjs — do not hand-edit === */'
export const END = '/* === end palette tokens === */'

export function walk(dir, out = []) {
  for (const e of readdirSync(dir)) {
    const p = join(dir, e)
    if (statSync(p).isDirectory()) walk(p, out)
    else if (/\.tsx?$/.test(e)) out.push(p)
  }
  return out
}

/** Every file a page's colour can come from: the app routes and the shared components. */
export function sourceFiles() {
  return [...walk(join(SRC, 'app')), ...walk(join(SRC, 'components'))]
}

export const HEX = /#(?:[0-9a-fA-F]{3}|[0-9a-fA-F]{6})\b/g
// A colour literal is not only a hex. These are the CSS colour KEYWORDS the call sites actually use —
// measured, not a copy of the CSS list — each with the value the browser gives it, so a keyword and the
// hex of the same colour resolve to ONE token. `transparent`, `currentColor`, `inherit` and `none` are
// deliberately absent: they are not colours, and a theme has nothing to say about them.
export const NAMED = {
  white: '#ffffff', black: '#000000', red: '#ff0000', green: '#008000',
  gray: '#808080', grey: '#808080', crimson: '#dc143c', seagreen: '#2e8b57',
}
export const NAMED_RE = new RegExp(`'(${Object.keys(NAMED).join('|')})'`, 'g')
/** `#abc` and `#AABBCC` are the same colour; the token is keyed by the six-digit lower-case form. */
export function canon(h) {
  h = h.toLowerCase()
  return h.length === 4 ? '#' + [1, 2, 3].map(i => h[i] + h[i]).join('') : h
}
// Which property a literal is the value of decides its role. Both lists are DECLARED, because a role
// this file guessed would be a role nobody could check: measured on the 4,275 call sites that do name
// their property, lightness alone predicts the role for only 70% of the fills, so guessing the rest
// would have mis-coloured hundreds of them. A literal on a property named in neither list is left
// alone and counted (see `ambiguous`) rather than converted on a hunch.
export const FG_PROPS = ['color', 'fill', 'stroke', 'caretColor', 'textDecorationColor',
  'columnRuleColor', 'fg', 'c', 'text', 'ink', 'textColor']
export const BG_PROPS = ['background', 'backgroundColor', 'bg', 'b', 'border', 'borderColor',
  'borderLeft', 'borderRight', 'borderTop', 'borderBottom', 'bd', 'boxShadow', 'outline',
  'outlineColor', 'borderBlock', 'borderInline', 'stopColor']
export function roleOf(prop) {
  return FG_PROPS.includes(prop) ? 'fg' : BG_PROPS.includes(prop) ? 'bg' : null
}

/** The property a literal at `index` is a value of — the nearest `name:` or `name=` before it. */
export const PROP_BEFORE = /([A-Za-z][A-Za-z0-9_-]*)\s*[:=]/g
export function propAt(src, index) {
  const before = src.slice(Math.max(0, index - 200), index)
  const all = [...before.matchAll(PROP_BEFORE)]
  return all.length ? all[all.length - 1][1] : null
}
/** Every place a colour literal appears, with the role it resolves to (null = we cannot tell). */
export function sites(files = sourceFiles()) {
  const out = []
  for (const f of files) {
    const src = readFileSync(f, 'utf8')
    for (const m of src.matchAll(HEX))
      out.push({ file: f, index: m.index, raw: m[0], colour: canon(m[0]), role: roleOf(propAt(src, m.index)) })
    // A keyword is only a colour when it is DIRECTLY the value of a colour property, and only after a
    // COLON: `type Lamp = 'green'` is a type, not a style. The looser
    // "nearest property within 200 characters" rule is right for a hex, which is a colour wherever it
    // appears, but `c.lamp !== 'green'` is a STATUS and converting it would have changed what the page
    // compares — caught by the type checker on admin/control-box, so the rule here is strict.
    for (const m of src.matchAll(NAMED_RE)) {
      const direct = src.slice(Math.max(0, m.index - 40), m.index).match(/([A-Za-z][A-Za-z0-9_-]*)\s*:\s*$/)
      if (direct) out.push({ file: f, index: m.index, raw: m[0], colour: NAMED[m[1]], quoted: true,
                             role: roleOf(direct[1]) })
    }
  }
  return out.sort((a, b) => (a.file === b.file ? a.index - b.index : a.file < b.file ? -1 : 1))
}
/** The call sites whose role is not declared — a measured debt, never a guess. */
export function ambiguous(files = sourceFiles()) { return sites(files).filter(s => !s.role) }

export const TOKEN_REF = /--c-((?:bg|fg)-[0-9a-f]{6})\b/g
/** Every (role, colour) pair the call sites USE, as `<role>-<hex>`, in a stable order.
 *
 *  A token the pages dereference and a literal still spelled at a call site both count, so running
 *  the generator is idempotent: once a literal has been converted its token is kept BECAUSE something
 *  reads it, and a token nothing reads any more drops out of the stylesheet on the next run. The one
 *  home is therefore derived from the callers, never a hand-kept list that could go stale. */
export function literals(files = sourceFiles()) {
  const keys = new Set(sites(files).filter(s => s.role).map(s => `${s.role}-${s.colour.slice(1)}`))
  for (const f of files) for (const m of readFileSync(f, 'utf8').matchAll(TOKEN_REF)) keys.add(m[1])
  return [...keys].sort()
}

// ——— the derivation ———————————————————————————————————————————————————————————————————————
// A dark counterpart keeps the colour's HUE (a red warning stays red) and mirrors its LIGHTNESS band,
// because what a pale tint and a dark ink are FOR swaps when the page goes black: the tint becomes a
// dark fill and the ink becomes the bright text on it. Saturation is eased on the extremes so a tint
// does not read as a second accent and bright text does not vibrate against the black.
export function rgb(hex) {
  return [1, 3, 5].map(i => parseInt(hex.slice(i, i + 2), 16))
}
export function hex(r, g, b) {
  return '#' + [r, g, b].map(v => Math.max(0, Math.min(255, Math.round(v))).toString(16).padStart(2, '0')).join('')
}
export function toHsl([r, g, b]) {
  r /= 255; g /= 255; b /= 255
  const mx = Math.max(r, g, b), mn = Math.min(r, g, b), d = mx - mn, l = (mx + mn) / 2
  let h = 0, s = 0
  if (d) {
    s = d / (1 - Math.abs(2 * l - 1))
    h = mx === r ? ((g - b) / d) % 6 : mx === g ? (b - r) / d + 2 : (r - g) / d + 4
    h *= 60; if (h < 0) h += 360
  }
  return [h, s, l]
}
export function fromHsl(h, s, l) {
  const c = (1 - Math.abs(2 * l - 1)) * s, x = c * (1 - Math.abs(((h / 60) % 2) - 1)), m = l - c / 2
  const [r, g, b] = h < 60 ? [c, x, 0] : h < 120 ? [x, c, 0] : h < 180 ? [0, c, x]
    : h < 240 ? [0, x, c] : h < 300 ? [x, 0, c] : [c, 0, x]
  return hex((r + m) * 255, (g + m) * 255, (b + m) * 255)
}

export function darkCounterpart(lit, role = 'bg') {
  lit = canon(lit)
  const [h, s, l] = toHsl(rgb(lit))
  if (role === 'fg') {
    // TEXT. Already-light lettering is there to sit on a coloured fill and is left exactly as it is —
    // that is the `#fff` on a button. Dark ink is what has to come up. A near-black ink is the page's
    // ordinary writing rather than a colour, so it returns as near-white keeping only a trace of hue;
    // a saturated ink keeps its hue and gains a little, because a red that must still read as a
    // WARNING cannot arrive on black as a pastel.
    if (l >= 0.72) return lit
    if (l < 0.20) return fromHsl(h, Math.min(s, 0.14), 0.90)
    return fromHsl(h, Math.min(0.92, s * 1.15), 0.80 - l * 0.15)
  }
  // A FILL, a border or a shadow. The page is black underneath and the writing on these fills is now
  // light, so every fill that was built to carry DARK text has to come down far enough to carry light
  // text instead — that is what the 0.60 line is: above it a colour was a tint behind dark ink, below
  // it the colour was already doing a dark job and is left alone. A colour that is already dark must
  // NOT be inverted: `#000` is a black panel on a white page and still a black panel on a black one.
  if (l >= 0.60) {
    const base = s < 0.06 ? 0.07 : 0.10
    return fromHsl(h, Math.min(s, 0.45), base + (1 - l) * 0.30)
  }
  if (l >= 0.40) return fromHsl(h, Math.min(s, 0.55), Math.max(0.16, l - 0.22))
  return lit
}

/** `bg-fef2f2` -> ['bg', '#fef2f2']. The token name carries no '#': it is not valid in an identifier. */
export function split(key) { const i = key.indexOf('-'); return [key.slice(0, i), '#' + key.slice(i + 1)] }

export function block(lits) {
  const light = lits.map(k => `  --c-${k}: ${split(k)[1]};`).join('\n')
  const dark = lits.map(k => { const [r, c] = split(k); return `  --c-${k}: ${darkCounterpart(c, r)};` }).join('\n')
  return [
    BEGIN,
    `/* ${lits.length} (role, colour) pairs the call sites dereference. The light column is each literal`,
    `   AS ITSELF, so the light theme cannot drift; the dark column is theme_palette.mjs's derivation. */`,
    ':root {', light, '}',
    ':root[data-theme="dark"] {', dark, '}',
    END,
  ].join('\n')
}

export function render(css, lits) {
  const b = css.indexOf(BEGIN), e = css.indexOf(END)
  if (b < 0 || e < 0) throw new Error('globals.css is missing the generated-palette markers')
  return css.slice(0, b) + block(lits) + css.slice(e + END.length)
}

if (process.argv.includes('--write')) {
  const lits = literals()
  writeFileSync(CSS, render(readFileSync(CSS, 'utf8'), lits))
  console.log(`palette: ${lits.length} literals written to globals.css`)
}
