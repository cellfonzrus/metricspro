-- 1107_pos_wholesale_w9.sql
-- THE WHOLESALE CUSTOMER AND THE W-9 THAT MAKES A SALE TAX-FREE (owner 2026-10-30, index §POS-16).
--
-- Owner, verbatim: *"add … a customer type as wholesale where the option to not charge tax will be
-- by default if the user confirms they received the filled out w9 and block the user to make a sale
-- before the system has an updated w9, only the admin can go past without an updated w9, give the
-- downloadable link to the user in case of a wholesale customer … and the option to email to the
-- customer and a return link for the customer to send the w9 back"*.
--
-- WHAT THIS CHANGES
--
--  1. `pos.customers.account_type` carried a CHECK of two values (mig 725) and the customer form
--     carried the same two words again. The list is now declared once in
--     `backend/app/modules/pos/wholesale_w9.py` (`ACCOUNT_TYPES`) and this constraint is GENERATED
--     from it — `harness_pos_wholesale_w9.py` §E fails the build if the two drift. The third value
--     is `Wholesale`.
--
--  2. `pos.customer_tax_doc` — ONE row per customer per document kind, holding the WHOLE life of
--     that certificate: that we asked for it (and the token the customer answers on), that it came
--     back, who confirmed it, where the file is, and when it goes out of date. Deliberately ONE
--     table and not a sibling "request" table: "where is this customer's W-9 up to" is one
--     question, and two tables answering it would drift the first time a customer sent a second
--     copy.
--
--  3. `pos.sales` gains `tax_exempt_basis` and `w9_override_by`. A tax-free sale must carry WHY it
--     was tax-free — a zero tax figure with no stated basis is exactly what an auditor asks about —
--     and a sale an admin allowed past a missing certificate must name that admin. Neither is
--     derivable afterwards: the certificate may be filed the next day, and the answer to "was it on
--     file when we sold" would then be lost.
--
-- NOTHING IS BACKFILLED AND NO MONEY MOVES. Every existing customer keeps its account type, every
-- existing sale keeps a NULL basis (correctly: it was a taxable sale), and no tax figure on any
-- stored row is touched. No tenant is named anywhere in this file (RULE TWO): whether wholesale is
-- tax-free, how long a W-9 stays current, whether a missing one blocks a sale and where the blank
-- form lives are all `pos.pos_settings` rows with house defaults.
--
-- THE TOKEN IS A CREDENTIAL. `return_token` is the only thing standing between an anonymous caller
-- and an upload slot, so it is generated by the APPLICATION from a cryptographic source (32 bytes,
-- url-safe), is unique, carries its own expiry, and is cleared when the document arrives. The
-- public endpoints answer an identical 404 for unknown / expired / already-used, so a probe learns
-- nothing. See index §POS-16.6.
--
-- REVERT: notes at the foot of the file.

-- ── 1. the customer type ────────────────────────────────────────────────────────────────────────
do $$
begin
  if exists (select 1 from pg_constraint
              where conrelid = 'pos.customers'::regclass
                and conname = 'customers_account_type_check') then
    alter table pos.customers drop constraint customers_account_type_check;
  end if;
  alter table pos.customers
    add constraint customers_account_type_check
    check (account_type in ('Personal','Business','Wholesale'));
end $$;

-- ── 2. where this customer's W-9 is up to ───────────────────────────────────────────────────────
create table if not exists pos.customer_tax_doc (
  id                 uuid primary key default gen_random_uuid(),
  org_id             uuid not null,
  customer_id        uuid not null references pos.customers(id) on delete cascade,
  kind               text not null default 'w9',
  -- requested → the form was sent and we are waiting; submitted → the customer sent something back;
  -- received  → a person CONFIRMED the filled-out form arrived (the only state that buys exemption);
  -- rejected  → what came back was not a usable certificate.
  status             text not null default 'requested'
                     check (status in ('requested','submitted','received','rejected')),
  requested_at       timestamptz,
  requested_by       text,                 -- storeops employee_id who sent the form
  requested_to_email text,                 -- the address it went to, as typed
  submitted_at       timestamptz,
  received_at        date,                 -- the day the signed form was confirmed received
  confirmed_by       text,                 -- storeops employee_id who confirmed it
  expires_at         date,                 -- the certificate's OWN expiry when it carries one
  file_path          text,                 -- object path in the documents bucket, never a URL
  file_format        text,                 -- what the bytes sniffed to (core/upload_format)
  return_token       text unique,          -- the customer's one-time return link; cleared on arrival
  token_expires_at   timestamptz,
  note               text,
  created_at         timestamptz default now(),
  updated_at         timestamptz default now(),
  unique (org_id, customer_id, kind)
);

create index if not exists pos_customer_tax_doc_customer
  on pos.customer_tax_doc(org_id, customer_id);
create index if not exists pos_customer_tax_doc_status
  on pos.customer_tax_doc(org_id, kind, status);
-- the public return endpoint's only lookup
create index if not exists pos_customer_tax_doc_token
  on pos.customer_tax_doc(return_token) where return_token is not null;

comment on table pos.customer_tax_doc is
  'ONE row per customer per tax-document kind, holding that document''s whole life: requested, '
  'submitted, confirmed received, expired. Read through pos/wholesale_w9.py — no caller judges '
  'whether a certificate is current (index §POS-16).';
comment on column pos.customer_tax_doc.return_token is
  'The customer''s one-time return link. A CREDENTIAL: generated by the app from secrets.token_urlsafe, '
  'expires, and is cleared the moment the document arrives. Never logged, never put in a redirect.';
comment on column pos.customer_tax_doc.status is
  'Only `received` buys a tax exemption, and only a person can set it — a customer''s own upload '
  'lands as `submitted` (owner: tax-free "if the user confirms they received the filled out w9").';

grant select, insert, update, delete on pos.customer_tax_doc to service_role;

-- ── 3. why a sale was tax-free, and who allowed it ──────────────────────────────────────────────
alter table pos.sales add column if not exists tax_exempt_basis text;
alter table pos.sales add column if not exists w9_override_by text;

comment on column pos.sales.tax_exempt_basis is
  'Why this sale charged no tax (pos/wholesale_w9.BASIS_W9 = ''w9_on_file''). NULL on a taxable '
  'sale. Recorded at checkout because it cannot be re-derived later: the certificate may be filed '
  'the next day, and "was it on file when we sold" would be lost.';
comment on column pos.sales.w9_override_by is
  'The admin who allowed this wholesale sale past a missing or out-of-date W-9. The sale is TAXABLE '
  '— an override permits a sale, it never supports an exemption.';

create index if not exists pos_sales_exempt
  on pos.sales(org_id, tax_exempt_basis) where tax_exempt_basis is not null;

grant select, insert, update, delete on pos.sales to service_role;
grant select, insert, update, delete on pos.customers to service_role;

-- ── 4. the checkout stores both new facts ───────────────────────────────────────────────────────
-- Body otherwise identical to mig 1106's (itself 745's). Only the pos.sales insert changes.
create or replace function pos.checkout(p_org uuid, p_sale jsonb, p_items jsonb, p_payments jsonb)
 returns pos.sales
 language plpgsql
 set search_path to 'pos', 'pg_temp'
as $function$
DECLARE
  v_sale pos.sales;
  it JSONB;
  pay JSONB;
BEGIN
  IF p_org IS NULL THEN
    RAISE EXCEPTION 'org is required';
  END IF;
  IF p_items IS NULL OR jsonb_typeof(p_items) <> 'array' OR jsonb_array_length(p_items) = 0 THEN
    RAISE EXCEPTION 'a sale needs at least one item';
  END IF;

  INSERT INTO pos.sales (org_id, store_code, customer_id, employee_id, receipt_type, status,
                         subtotal, discount_total, tax_total, total, balance, is_activation_sale,
                         receipt, notes, tax_exempt_basis, w9_override_by)
  VALUES (
    p_org,
    NULLIF(btrim(COALESCE(p_sale->>'store_code', '')), ''),
    NULLIF(p_sale->>'customer_id', '')::uuid,
    NULLIF(btrim(COALESCE(p_sale->>'employee_id', '')), ''),
    COALESCE(NULLIF(p_sale->>'receipt_type', ''), 'sale'),
    'completed',
    COALESCE((p_sale->>'subtotal')::numeric, 0),
    COALESCE((p_sale->>'discount_total')::numeric, 0),
    COALESCE((p_sale->>'tax_total')::numeric, 0),
    COALESCE((p_sale->>'total')::numeric, 0),
    COALESCE((p_sale->>'balance')::numeric, 0),
    COALESCE((p_sale->>'is_activation_sale')::boolean, false),
    p_sale->'receipt',
    NULLIF(p_sale->>'notes', ''),
    NULLIF(p_sale->>'tax_exempt_basis', ''),
    NULLIF(p_sale->>'w9_override_by', '')
  )
  RETURNING * INTO v_sale;

  FOR it IN SELECT * FROM jsonb_array_elements(p_items) LOOP
    INSERT INTO pos.sale_items (org_id, sale_id, product_id, product_type, description,
                                serial_number, qty, unit_price, list_price, cost, discount,
                                tax_rate, tax_value, extended_price)
    VALUES (
      p_org, v_sale.id,
      (it->>'product_id')::uuid,
      NULLIF(it->>'product_type', ''),
      NULLIF(it->>'description', ''),
      NULLIF(btrim(COALESCE(it->>'serial_number', '')), ''),
      COALESCE((it->>'qty')::int, 1),
      COALESCE((it->>'unit_price')::numeric, 0),
      COALESCE((it->>'list_price')::numeric, (it->>'unit_price')::numeric, 0),
      (it->>'cost')::numeric,
      COALESCE((it->>'discount')::numeric, 0),
      COALESCE((it->>'tax_rate')::numeric, 0),
      COALESCE((it->>'tax_value')::numeric, 0),
      COALESCE((it->>'extended_price')::numeric, 0)
    );
  END LOOP;

  IF p_payments IS NOT NULL AND jsonb_typeof(p_payments) = 'array' THEN
    FOR pay IN SELECT * FROM jsonb_array_elements(p_payments) LOOP
      INSERT INTO pos.sale_payments (org_id, sale_id, payment_method, amount,
                                     card_last_four, check_number, terms_days, due_date)
      VALUES (
        p_org, v_sale.id,
        pay->>'payment_method',
        COALESCE((pay->>'amount')::numeric, 0),
        NULLIF(pay->>'card_last_four', ''),
        NULLIF(pay->>'check_number', ''),
        NULLIF(pay->>'terms_days', '')::int,
        NULLIF(pay->>'due_date', '')::date
      );
    END LOOP;
  END IF;

  RETURN v_sale;
END;
$function$;

select '1107 complete — wholesale customers, their W-9 and why a sale was tax-free' as status;

