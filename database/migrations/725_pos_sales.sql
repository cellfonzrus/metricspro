-- ── Sales ──────────────────────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS pos.sales (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  org_id UUID NOT NULL,
  transaction_id BIGINT GENERATED BY DEFAULT AS IDENTITY,   -- human-facing receipt #
  store_code TEXT,
  customer_id UUID REFERENCES pos.customers(id),
  employee_id TEXT,                   -- selling rep (storeops employee_id)
  receipt_type TEXT DEFAULT 'sale',
  status TEXT DEFAULT 'completed' CHECK (status IN ('completed','voided')),
  subtotal NUMERIC(12,2) DEFAULT 0,   -- net of line discounts, tax-exclusive
  discount_total NUMERIC(12,2) DEFAULT 0,
  tax_total NUMERIC(12,2) DEFAULT 0,
  total NUMERIC(12,2) DEFAULT 0,      -- subtotal + tax_total
  balance NUMERIC(12,2) DEFAULT 0,
  is_activation_sale BOOLEAN DEFAULT false,
  receipt JSONB,                      -- full receipt snapshot at checkout (incl. tendered/change)
  voided_at TIMESTAMPTZ,
  voided_by TEXT,                     -- employee_id who voided
  notes TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW(),
  UNIQUE (org_id, transaction_id)
);
CREATE INDEX IF NOT EXISTS pos_sales_org_created ON pos.sales(org_id, created_at DESC);
CREATE INDEX IF NOT EXISTS pos_sales_store ON pos.sales(org_id, store_code, created_at DESC);

CREATE TABLE IF NOT EXISTS pos.sale_items (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  org_id UUID NOT NULL,
  sale_id UUID NOT NULL REFERENCES pos.sales(id) ON DELETE CASCADE,
  product_id UUID NOT NULL REFERENCES pos.products(id),
  product_type TEXT,
  description TEXT,
  serial_number TEXT,                 -- non-empty ⇒ serial-tracked unit; drives the inventory trigger branch
  qty INTEGER NOT NULL DEFAULT 1,
  unit_price NUMERIC(12,2) NOT NULL,
  cost NUMERIC(12,2),                 -- snapshot of products.cost (cost_based tax)
  discount NUMERIC(12,2) DEFAULT 0,   -- per unit
  tax_rate NUMERIC(8,6) DEFAULT 0,    -- FRACTION (0.08875), not percent
  tax_value NUMERIC(12,2) DEFAULT 0,  -- line level: per-unit tax × qty
  extended_price NUMERIC(12,2) NOT NULL,  -- (unit_price − discount + per_unit_tax) × qty (tax-inclusive)
  created_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS pos_sale_items_sale ON pos.sale_items(sale_id);

