-- ── POS settings kv (config engine) ────────────────────────────────────────────────────────────────
-- One jsonb value per key: org default (store_code null) or per-store override. Effective value =
-- store override ?? org default ?? code-side default (frontend/src/lib/pos-config.ts registry).
CREATE TABLE IF NOT EXISTS pos.pos_settings (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  org_id UUID NOT NULL,
  store_code TEXT,                    -- null = org-level default row
  key TEXT NOT NULL,
  value JSONB NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE UNIQUE INDEX IF NOT EXISTS pos_settings_org_key
  ON pos.pos_settings (org_id, key) WHERE store_code IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS pos_settings_store_key
  ON pos.pos_settings (org_id, store_code, key) WHERE store_code IS NOT NULL;

-- Effective value for one key: store override → org default → null (caller falls back to the
-- code-side default).
CREATE OR REPLACE FUNCTION pos.pos_setting(p_org UUID, p_store TEXT, p_key TEXT)
RETURNS JSONB
LANGUAGE sql
STABLE
SET search_path = pos, pg_temp
AS $$
  SELECT value FROM (
    SELECT value, 1 AS pri FROM pos.pos_settings
      WHERE org_id = p_org AND store_code = p_store AND p_store IS NOT NULL AND key = p_key
    UNION ALL
    SELECT value, 2 FROM pos.pos_settings
      WHERE org_id = p_org AND store_code IS NULL AND key = p_key
  ) v ORDER BY pri LIMIT 1;
$$;

