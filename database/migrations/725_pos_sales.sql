-- MIGRATION 725: POS MODULE — PHASE 1: CUSTOMERS, INVENTORY, SALES/CHECKOUT, REGISTER, CONFIG
-- Run this in the Supabase SQL editor (after 724). Idempotent.
--
-- Ports the transactional core of the standalone pos-system app into the pos.* schema:
--   customers (+ encrypted PII), customer notes, serial + standard inventory,
--   sales/sale_items/sale_payments with an ATOMIC pos.checkout() (the old app did three
--   separate client inserts — a partial sale was a reachable state), void_sale,
--   register (cash drawer) sessions with server-computed variance, the pos_settings
--   config kv (org default → per-store override), tax codes, and receipt templates.
--
-- Identity conventions (same as every module, see mig 724 header):
--   * org_id UUID on every row.
--   * stores referenced by storeops.stores.store_code (TEXT), column name store_code.
--   * employees referenced by storeops.employees.employee_id (TEXT business key —
--     NEVER the numeric PK, see mig 415).
--   * No auth.uid() anywhere: the backend calls with the service role and passes the
--     acting employee explicitly; RBAC lives in the FastAPI layer.
--
-- Differences from the standalone app, on purpose:
--   * sales.receipt JSONB — full receipt snapshot at checkout (the old app kept
--     tendered/change only in React state; they were unrecoverable after the modal).
--   * org_settings.tax_applied_on became the pos_settings key 'tax_applied_on'.
--   * Columns the old code never touched (dnb_number, price_profile, precash_account_no,
--     home_location_id, assigned_sales_rep_id) are dropped; Phase 3 data migration can
--     re-add if real data shows up in them.

CREATE SCHEMA IF NOT EXISTS pos;

-- ── Customers ──────────────────────────────────────────────────────────────────────────────────────
-- PII: ssn/driver-license ciphertext only (pgp_sym_encrypt, key in Vault). The database never
-- holds plaintext; access only via the pos.customer_pii_* functions below.
CREATE TABLE IF NOT EXISTS pos.customers (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  org_id UUID NOT NULL,
  cust_number BIGINT GENERATED BY DEFAULT AS IDENTITY,
  account_type TEXT DEFAULT 'Personal' CHECK (account_type IN ('Personal','Business')),
  company_name TEXT,
  first_name TEXT,
  last_name TEXT,
  middle_initial TEXT,
  dob DATE,
  driver_license_state TEXT,          -- 2-letter code; deliberately plaintext (filterable, not sensitive alone)
  primary_account_no TEXT,
  password TEXT,                      -- carrier "account password/PIN" the customer sets, not a login credential
  email TEXT,
  phone_primary TEXT,
  phone_secondary TEXT,
  address_1 TEXT,
  address_2 TEXT,
  city TEXT,
  state TEXT,
  zip TEXT,
  referral_source TEXT,
  credit_limit NUMERIC(12,2) DEFAULT 0,
  accept_checks BOOLEAN DEFAULT false,
  is_active BOOLEAN DEFAULT true,
  ssn_enc BYTEA,                      -- pgp_sym_encrypt(ssn, vault:pos_pii_encryption_key)
  driver_license_enc BYTEA,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW(),
  UNIQUE (org_id, cust_number)
);
CREATE INDEX IF NOT EXISTS pos_customers_org_active ON pos.customers(org_id, is_active);
CREATE INDEX IF NOT EXISTS pos_customers_phone ON pos.customers(org_id, phone_primary);
CREATE INDEX IF NOT EXISTS pos_customers_name ON pos.customers(org_id, last_name, first_name);

COMMENT ON COLUMN pos.customers.ssn_enc IS
  'pgp_sym_encrypt(ssn, vault:pos_pii_encryption_key). Read/write only via pos.customer_pii_*.';
COMMENT ON COLUMN pos.customers.driver_license_enc IS
  'pgp_sym_encrypt(driver_license_num, vault:pos_pii_encryption_key). Read/write only via pos.customer_pii_*.';

