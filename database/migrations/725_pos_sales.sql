CREATE OR REPLACE FUNCTION pos.open_register(
  p_org UUID,
  p_store TEXT,
  p_register INT DEFAULT 1,
  p_employee TEXT DEFAULT NULL,
  p_float NUMERIC DEFAULT 0,
  p_denominations JSONB DEFAULT NULL
)
RETURNS pos.register_sessions
LANGUAGE plpgsql
SET search_path = pos, pg_temp
AS $$
DECLARE
  v_row pos.register_sessions;
BEGIN
  IF p_org IS NULL OR p_store IS NULL OR btrim(p_store) = '' THEN
    RAISE EXCEPTION 'org and store are required';
  END IF;
  IF p_float IS NULL OR p_float < 0 THEN
    RAISE EXCEPTION 'opening float must be zero or more';
  END IF;

  INSERT INTO pos.register_sessions
    (org_id, store_code, register_number, opened_by, opening_float, opening_denominations)
  VALUES (p_org, p_store, COALESCE(p_register, 1), NULLIF(btrim(COALESCE(p_employee, '')), ''),
          p_float, p_denominations)
  RETURNING * INTO v_row;
  RETURN v_row;
EXCEPTION WHEN unique_violation THEN
  RAISE EXCEPTION 'register % at this store is already open — close it first', COALESCE(p_register, 1);
END;
$$;

-- Close: expected cash = opening float + cash payments on non-voided sales at this store since
-- open. Variance = counted − expected, computed HERE (the client never computes expected).
CREATE OR REPLACE FUNCTION pos.close_register(
  p_org UUID,
  p_session UUID,
  p_counted NUMERIC,
  p_employee TEXT DEFAULT NULL,
  p_denominations JSONB DEFAULT NULL,
  p_notes TEXT DEFAULT NULL
)
RETURNS pos.register_sessions
LANGUAGE plpgsql
SET search_path = pos, pg_temp
AS $$
DECLARE
  s pos.register_sessions;
  v_cash NUMERIC;
  v_expected NUMERIC;
BEGIN
  SELECT * INTO s FROM pos.register_sessions WHERE id = p_session AND org_id = p_org;
  IF s.id IS NULL THEN
    RAISE EXCEPTION 'register session not found';
  END IF;
  IF s.status <> 'open' THEN
    RAISE EXCEPTION 'this register session is already closed';
  END IF;
  IF p_counted IS NULL OR p_counted < 0 THEN
    RAISE EXCEPTION 'counted cash must be zero or more';
  END IF;

  SELECT COALESCE(SUM(sp.amount), 0) INTO v_cash
  FROM pos.sale_payments sp
  JOIN pos.sales sa ON sa.id = sp.sale_id
  WHERE sa.org_id = s.org_id
    AND sa.store_code = s.store_code
    AND sa.created_at >= s.opened_at
    AND COALESCE(sa.status, 'completed') <> 'voided'
    AND sp.payment_method = 'cash';

  v_expected := s.opening_float + v_cash;

  UPDATE pos.register_sessions
     SET status = 'closed',
         closed_by = NULLIF(btrim(COALESCE(p_employee, '')), ''),
         closed_at = NOW(),
         closing_counted = p_counted,
         closing_expected = v_expected,
         variance = p_counted - v_expected,
         closing_denominations = p_denominations,
         notes = p_notes
   WHERE id = p_session
   RETURNING * INTO s;
  RETURN s;
END;
$$;

-- ── Inventory movement on checkout ─────────────────────────────────────────────────────────────────
-- AFTER INSERT trigger on sale_items: same transaction as the item insert, so a failed movement
-- can never half-apply. Serial items flip to 'sold'; standard items decrement the store's count.
-- Honors the 'allow_negative_inventory' setting (blocks below-zero sales when off).
CREATE OR REPLACE FUNCTION pos.apply_sale_item_inventory()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pos, pg_temp
AS $$
DECLARE
  v_store TEXT;
  v_allow BOOLEAN;
  v_on_hand NUMERIC;
BEGIN
  SELECT s.store_code INTO v_store FROM pos.sales s WHERE s.id = NEW.sale_id;

  IF NEW.serial_number IS NOT NULL AND btrim(NEW.serial_number) <> '' THEN
    UPDATE pos.inventory_serial i
       SET status = 'sold', sold_at = NOW(), sold_in_sale_id = NEW.sale_id, updated_at = NOW()
     WHERE i.org_id = NEW.org_id
       AND i.serial_number = NEW.serial_number
       AND i.status IN ('in_stock', 'in_transit');
    -- not found ⇒ unit wasn't tracked; the sale proceeds (serials aren't validated at the register)
  ELSIF v_store IS NOT NULL THEN
    v_allow := COALESCE((pos.pos_setting(NEW.org_id, v_store, 'allow_negative_inventory') #>> '{}')::boolean, true);
    IF NOT v_allow THEN
      SELECT st.qty_on_hand INTO v_on_hand FROM pos.inventory_standard st
       WHERE st.org_id = NEW.org_id AND st.product_id = NEW.product_id AND st.store_code = v_store;
      IF COALESCE(v_on_hand, 0) - COALESCE(NEW.qty, 0) < 0 THEN
        RAISE EXCEPTION 'Not enough stock for "%" (% on hand) — selling below zero is disabled in POS Settings.',
          COALESCE(NEW.description, 'item'), COALESCE(v_on_hand, 0);
      END IF;
    END IF;
    UPDATE pos.inventory_standard st
       SET qty_on_hand = st.qty_on_hand - COALESCE(NEW.qty, 0), updated_at = NOW()
     WHERE st.org_id = NEW.org_id
       AND st.product_id = NEW.product_id
       AND st.store_code = v_store;
    -- negative quantities allowed by default: they surface count discrepancies instead of
    -- blocking a real cash sale.
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS apply_sale_item_inventory ON pos.sale_items;
CREATE TRIGGER apply_sale_item_inventory
  AFTER INSERT ON pos.sale_items
  FOR EACH ROW EXECUTE FUNCTION pos.apply_sale_item_inventory();

-- ── Atomic checkout ────────────────────────────────────────────────────────────────────────────────
-- One call inserts the sale + items + payments in a single transaction (the standalone app's three
-- client round-trips could strand a header-only sale). Item inserts fire the inventory trigger.
-- p_sale: {store_code, customer_id, employee_id, receipt_type, subtotal, discount_total, tax_total,
--          total, balance, is_activation_sale, receipt, notes}
-- p_items: [{product_id, product_type, description, serial_number, qty, unit_price, cost, discount,
--            tax_rate, tax_value, extended_price}]
-- p_payments: [{payment_method, amount, card_last_four, check_number}]
CREATE OR REPLACE FUNCTION pos.checkout(
  p_org UUID,
  p_sale JSONB,
  p_items JSONB,
  p_payments JSONB
)
RETURNS pos.sales
LANGUAGE plpgsql
SET search_path = pos, pg_temp
AS $$
DECLARE
  v_sale pos.sales;
  it JSONB;
  pay JSONB;
BEGIN
  IF p_org IS NULL THEN
    RAISE EXCEPTION 'org is required';
  END IF;
  IF p_items IS NULL OR jsonb_typeof(p_items) <> 'array' OR jsonb_array_length(p_items) = 0 THEN
    RAISE EXCEPTION 'a sale needs at least one item';
  END IF;

  INSERT INTO pos.sales (org_id, store_code, customer_id, employee_id, receipt_type, status,
                         subtotal, discount_total, tax_total, total, balance, is_activation_sale,
                         receipt, notes)
  VALUES (
    p_org,
    NULLIF(btrim(COALESCE(p_sale->>'store_code', '')), ''),
    NULLIF(p_sale->>'customer_id', '')::uuid,
    NULLIF(btrim(COALESCE(p_sale->>'employee_id', '')), ''),
    COALESCE(NULLIF(p_sale->>'receipt_type', ''), 'sale'),
    'completed',
    COALESCE((p_sale->>'subtotal')::numeric, 0),
    COALESCE((p_sale->>'discount_total')::numeric, 0),
    COALESCE((p_sale->>'tax_total')::numeric, 0),
    COALESCE((p_sale->>'total')::numeric, 0),
    COALESCE((p_sale->>'balance')::numeric, 0),
    COALESCE((p_sale->>'is_activation_sale')::boolean, false),
    p_sale->'receipt',
    NULLIF(p_sale->>'notes', '')
  )
  RETURNING * INTO v_sale;

  FOR it IN SELECT * FROM jsonb_array_elements(p_items) LOOP
    INSERT INTO pos.sale_items (org_id, sale_id, product_id, product_type, description,
                                serial_number, qty, unit_price, cost, discount, tax_rate,
                                tax_value, extended_price)
    VALUES (
      p_org, v_sale.id,
      (it->>'product_id')::uuid,
      NULLIF(it->>'product_type', ''),
      NULLIF(it->>'description', ''),
      NULLIF(btrim(COALESCE(it->>'serial_number', '')), ''),
      COALESCE((it->>'qty')::int, 1),
      COALESCE((it->>'unit_price')::numeric, 0),
      (it->>'cost')::numeric,
      COALESCE((it->>'discount')::numeric, 0),
      COALESCE((it->>'tax_rate')::numeric, 0),
      COALESCE((it->>'tax_value')::numeric, 0),
      COALESCE((it->>'extended_price')::numeric, 0)
    );
  END LOOP;

  IF p_payments IS NOT NULL AND jsonb_typeof(p_payments) = 'array' THEN
    FOR pay IN SELECT * FROM jsonb_array_elements(p_payments) LOOP
      INSERT INTO pos.sale_payments (org_id, sale_id, payment_method, amount,
                                     card_last_four, check_number)
      VALUES (
        p_org, v_sale.id,
        pay->>'payment_method',
        COALESCE((pay->>'amount')::numeric, 0),
        NULLIF(pay->>'card_last_four', ''),
        NULLIF(pay->>'check_number', '')
      );
    END LOOP;
  END IF;

  RETURN v_sale;
END;
$$;

-- ── Void: atomic reversal ──────────────────────────────────────────────────────────────────────────
-- RBAC (who may void) is enforced in the FastAPI layer; this function only does the mechanics.
CREATE OR REPLACE FUNCTION pos.void_sale(p_org UUID, p_sale UUID, p_employee TEXT DEFAULT NULL)
RETURNS pos.sales
LANGUAGE plpgsql
SET search_path = pos, pg_temp
AS $$
DECLARE
  s pos.sales;
  it RECORD;
BEGIN
  SELECT * INTO s FROM pos.sales WHERE id = p_sale AND org_id = p_org;
  IF s.id IS NULL THEN
    RAISE EXCEPTION 'sale not found';
  END IF;
  IF s.status = 'voided' OR s.voided_at IS NOT NULL THEN
    RAISE EXCEPTION 'transaction #% is already voided', s.transaction_id;
  END IF;

  FOR it IN SELECT * FROM pos.sale_items WHERE sale_id = p_sale LOOP
    IF it.serial_number IS NOT NULL AND btrim(it.serial_number) <> '' THEN
      UPDATE pos.inventory_serial i
         SET status = 'in_stock', sold_at = NULL, sold_in_sale_id = NULL, updated_at = NOW()
       WHERE i.org_id = s.org_id
         AND i.serial_number = it.serial_number
         AND i.sold_in_sale_id = p_sale;
    ELSIF s.store_code IS NOT NULL THEN
      UPDATE pos.inventory_standard st
         SET qty_on_hand = st.qty_on_hand + COALESCE(it.qty, 0), updated_at = NOW()
       WHERE st.org_id = s.org_id
         AND st.product_id = it.product_id
         AND st.store_code = s.store_code;
    END IF;
  END LOOP;

  UPDATE pos.sales
     SET status = 'voided', voided_at = NOW(),
         voided_by = NULLIF(btrim(COALESCE(p_employee, '')), ''),
         updated_at = NOW()
   WHERE id = p_sale
   RETURNING * INTO s;
  RETURN s;
END;
$$;

-- ── PII encryption (Vault + pgcrypto) ──────────────────────────────────────────────────────────────
-- Same design as the standalone app's 20260806090003: key lives in Vault, never in a table or in
-- application code; the database holds ciphertext only. Differences: functions take an explicit
-- p_org (no auth.uid() — the backend is the only caller) and WHO may read full PII is a FastAPI
-- RBAC decision. The org check here is the belt-and-suspenders tenancy guard.
CREATE EXTENSION IF NOT EXISTS pgcrypto WITH SCHEMA extensions;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM vault.secrets WHERE name = 'pos_pii_encryption_key') THEN
    PERFORM vault.create_secret(
      encode(extensions.gen_random_bytes(32), 'hex'),
      'pos_pii_encryption_key',
      'Symmetric key for pos.customers PII columns (pgp_sym_encrypt); do not delete or rotate without re-encrypting ssn_enc / driver_license_enc'
    );
  END IF;
END $$;

-- The ONLY reader of the vault secret. SECURITY DEFINER to read vault.decrypted_secrets;
-- EXECUTE revoked from every client role below (the sibling definer functions are the only
-- callers — the function owner always has EXECUTE on its own functions).
CREATE OR REPLACE FUNCTION pos.pii_key()
RETURNS TEXT
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = pos, pg_temp
AS $$
  SELECT ds.decrypted_secret
  FROM vault.decrypted_secrets ds
  WHERE ds.name = 'pos_pii_encryption_key';
$$;
REVOKE ALL ON FUNCTION pos.pii_key() FROM public, anon, authenticated;

CREATE OR REPLACE FUNCTION pos.customer_pii_set(
  p_org UUID,
  p_customer UUID,
  p_ssn TEXT,
  p_driver_license TEXT
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pos, pg_temp
AS $$
DECLARE
  k TEXT;
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pos.customers c WHERE c.id = p_customer AND c.org_id = p_org) THEN
    RAISE EXCEPTION 'customer not found';
  END IF;
  k := pos.pii_key();
  -- PER-COLUMN semantics (owner constraint 2026-08-08: nothing may delete what it did not
  -- write). Previously BOTH columns were rewritten on every call, so saving only a driver
  -- licence NULLed the SSN ciphertext — and the plaintext exists nowhere else, so that loss
  -- was irreversible. Now:
  --   p_* IS NULL       ⇒ field omitted by the caller ⇒ leave the stored value untouched
  --   p_* = '' (blank)  ⇒ caller explicitly cleared the field ⇒ set NULL
  --   otherwise         ⇒ encrypt and store
  -- The omission case is the common one, so it is the one that must be safe by default.
  UPDATE pos.customers c
     SET ssn_enc = CASE
                     WHEN p_ssn IS NULL THEN c.ssn_enc
                     WHEN btrim(p_ssn) = '' THEN NULL
                     ELSE extensions.pgp_sym_encrypt(btrim(p_ssn), k)
                   END,
         driver_license_enc = CASE
                     WHEN p_driver_license IS NULL THEN c.driver_license_enc
                     WHEN btrim(p_driver_license) = '' THEN NULL
                     ELSE extensions.pgp_sym_encrypt(btrim(p_driver_license), k)
                   END,
         updated_at = NOW()
   WHERE c.id = p_customer;
END;
$$;
REVOKE ALL ON FUNCTION pos.customer_pii_set(UUID, UUID, TEXT, TEXT) FROM public, anon, authenticated;

CREATE OR REPLACE FUNCTION pos.customer_pii_get(p_org UUID, p_customer UUID)
RETURNS TABLE (ssn TEXT, driver_license_num TEXT)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pos, pg_temp
AS $$
DECLARE
  k TEXT;
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pos.customers c WHERE c.id = p_customer AND c.org_id = p_org) THEN
    RAISE EXCEPTION 'customer not found';
  END IF;
