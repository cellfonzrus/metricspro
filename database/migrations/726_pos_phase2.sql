-- Atomic create: header + items in one transaction (the standalone app inserted the header,
-- then the items, deleting the header by hand when the items failed).
-- p_header: {transfer_number, from_store_code, to_store_code, created_by, notes}
-- p_items:  [{product_id, qty, serial_number}]
CREATE OR REPLACE FUNCTION pos.create_transfer(p_org UUID, p_header JSONB, p_items JSONB)
RETURNS pos.store_transfers
LANGUAGE plpgsql
SET search_path = pos, pg_temp
AS $$
DECLARE
  v_row pos.store_transfers;
  it JSONB;
BEGIN
  IF p_org IS NULL THEN
    RAISE EXCEPTION 'org is required';
  END IF;
  IF p_items IS NULL OR jsonb_typeof(p_items) <> 'array' OR jsonb_array_length(p_items) = 0 THEN
    RAISE EXCEPTION 'a transfer needs at least one item';
  END IF;
  IF NULLIF(btrim(COALESCE(p_header->>'from_store_code', '')), '') IS NULL
     OR NULLIF(btrim(COALESCE(p_header->>'to_store_code', '')), '') IS NULL THEN
    RAISE EXCEPTION 'source and destination stores are required';
  END IF;
  IF (p_header->>'from_store_code') = (p_header->>'to_store_code') THEN
    RAISE EXCEPTION 'source and destination must be different stores';
  END IF;

  INSERT INTO pos.store_transfers (org_id, transfer_number, from_store_code, to_store_code,
                                   created_by, status, notes)
  VALUES (
    p_org,
    p_header->>'transfer_number',
    p_header->>'from_store_code',
    p_header->>'to_store_code',
    NULLIF(btrim(COALESCE(p_header->>'created_by', '')), ''),
    'pending',
    NULLIF(p_header->>'notes', '')
  )
  RETURNING * INTO v_row;

  FOR it IN SELECT * FROM jsonb_array_elements(p_items) LOOP
    INSERT INTO pos.store_transfer_items (org_id, transfer_id, product_id, qty, serial_number)
    VALUES (
      p_org, v_row.id,
      (it->>'product_id')::uuid,
      COALESCE((it->>'qty')::int, 1),
      NULLIF(btrim(COALESCE(it->>'serial_number', '')), '')
    );
  END LOOP;

  RETURN v_row;
END;
$$;

-- Ship: serials flip to in_transit, standard stock decrements at the source (with a FOR UPDATE
-- stock check). Ported from the standalone ship_transfer RPC; RBAC moved to the FastAPI layer.
CREATE OR REPLACE FUNCTION pos.ship_transfer(p_org UUID, p_transfer UUID)
RETURNS pos.store_transfers
LANGUAGE plpgsql
SET search_path = pos, pg_temp
AS $$
DECLARE
  t pos.store_transfers;
  it RECORD;
  v_have INTEGER;
BEGIN
  SELECT * INTO t FROM pos.store_transfers WHERE id = p_transfer AND org_id = p_org;
  IF t.id IS NULL THEN
    RAISE EXCEPTION 'transfer not found';
  END IF;
  IF t.status IS DISTINCT FROM 'pending' THEN
    RAISE EXCEPTION 'transfer % is %, only pending transfers can ship', t.transfer_number, t.status;
  END IF;

  FOR it IN SELECT * FROM pos.store_transfer_items WHERE transfer_id = p_transfer LOOP
    IF it.serial_number IS NOT NULL AND btrim(it.serial_number) <> '' THEN
      UPDATE pos.inventory_serial s
         SET status = 'in_transit', updated_at = NOW()
       WHERE s.org_id = t.org_id
         AND s.serial_number = it.serial_number
         AND s.store_code = t.from_store_code
         AND s.status = 'in_stock';
      IF NOT FOUND THEN
        RAISE EXCEPTION 'serial % is not in stock at the source store', it.serial_number;
      END IF;
    ELSE
      SELECT qty_on_hand INTO v_have
      FROM pos.inventory_standard
      WHERE org_id = t.org_id AND product_id = it.product_id
        AND store_code = t.from_store_code
      FOR UPDATE;
      IF COALESCE(v_have, 0) < COALESCE(it.qty, 0) THEN
        RAISE EXCEPTION 'insufficient stock to ship % units (have %)', it.qty, COALESCE(v_have, 0);
      END IF;
      UPDATE pos.inventory_standard
         SET qty_on_hand = qty_on_hand - it.qty, updated_at = NOW()
       WHERE org_id = t.org_id AND product_id = it.product_id
         AND store_code = t.from_store_code;
    END IF;
  END LOOP;

  UPDATE pos.store_transfers
     SET status = 'shipped', shipped_at = NOW()
   WHERE id = p_transfer
   RETURNING * INTO t;
  RETURN t;
END;
$$;

-- Receive: serials land in_stock at the destination, standard stock upserts. Ported from the
-- standalone receive_transfer RPC.
CREATE OR REPLACE FUNCTION pos.receive_transfer(p_org UUID, p_transfer UUID)
RETURNS pos.store_transfers
LANGUAGE plpgsql
SET search_path = pos, pg_temp
AS $$
DECLARE
  t pos.store_transfers;
  it RECORD;
BEGIN
  SELECT * INTO t FROM pos.store_transfers WHERE id = p_transfer AND org_id = p_org;
  IF t.id IS NULL THEN
    RAISE EXCEPTION 'transfer not found';
  END IF;
  IF t.status IS DISTINCT FROM 'shipped' THEN
    RAISE EXCEPTION 'transfer % is %, only shipped transfers can be received', t.transfer_number, t.status;
  END IF;

  FOR it IN SELECT * FROM pos.store_transfer_items WHERE transfer_id = p_transfer LOOP
    IF it.serial_number IS NOT NULL AND btrim(it.serial_number) <> '' THEN
      UPDATE pos.inventory_serial s
         SET status = 'in_stock', store_code = t.to_store_code, updated_at = NOW()
       WHERE s.org_id = t.org_id
         AND s.serial_number = it.serial_number
         AND s.status = 'in_transit';
      IF NOT FOUND THEN
        RAISE EXCEPTION 'serial % is not in transit on this transfer', it.serial_number;
      END IF;
    ELSE
      INSERT INTO pos.inventory_standard (org_id, product_id, store_code, qty_on_hand)
      VALUES (t.org_id, it.product_id, t.to_store_code, it.qty)
      ON CONFLICT (org_id, product_id, store_code)
      DO UPDATE SET qty_on_hand = pos.inventory_standard.qty_on_hand + EXCLUDED.qty_on_hand,
                    updated_at = NOW();
    END IF;
  END LOOP;

  UPDATE pos.store_transfers
     SET status = 'received', received_at = NOW()
   WHERE id = p_transfer
   RETURNING * INTO t;
  RETURN t;
END;
$$;

