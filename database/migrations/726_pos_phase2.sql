-- MIGRATION 726: POS MODULE — PHASE 2: ACTIVATIONS, VENDORS, PURCHASE ORDERS, TRANSFERS
-- Run this in the Supabase SQL editor (after 725). Idempotent.
--
-- Ports the rest of the standalone pos-system app's data model into pos.*:
--   activations (+ service plans catalog, dealer codes, carrier credit-check portals,
--   activation notes, trade-ins), vendors, purchase orders (+ items, unused by the UI yet
--   but kept for the receiving flow to come), store-to-store transfers with ATOMIC
--   create/ship/receive functions (ship/receive port the standalone RPCs; create is new —
--   the old app did a 2-step client insert with manual rollback).
--
-- Identity conventions (same as 724/725): org_id UUID on every row; stores by
-- storeops.stores.store_code TEXT; employees by storeops.employees.employee_id TEXT;
-- no auth.uid() — RBAC lives in the FastAPI layer.

CREATE SCHEMA IF NOT EXISTS pos;

-- ── Service plans catalog ──────────────────────────────────────────────────────────────────────────
