  special_promo TEXT,
  status TEXT DEFAULT 'active' CHECK (status IN ('active','cancelled','transferred')),
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW(),
