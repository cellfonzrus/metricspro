  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  org_id UUID NOT NULL,
  activation_number BIGINT GENERATED BY DEFAULT AS IDENTITY,
  sale_id UUID REFERENCES pos.sales(id) ON DELETE SET NULL,
  customer_id UUID REFERENCES pos.customers(id) ON DELETE SET NULL,
  store_code TEXT,
  employee_id TEXT,                   -- selling rep (storeops employee_id)
  carrier TEXT,
  activation_date DATE,
  service_plan_date DATE,
  service_plan_id UUID REFERENCES pos.service_plans(id) ON DELETE SET NULL,
  plan_code TEXT,
  plan_description TEXT,
  monthly_fee NUMERIC(10,2),
  included_minutes INTEGER,
  service_area TEXT,
  contract_type TEXT,
  contract_terms TEXT,
  dealer_code TEXT,
  cell_number TEXT,
  phone_serial TEXT,
  phone_model TEXT,
